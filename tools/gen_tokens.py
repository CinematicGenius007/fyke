#!/usr/bin/env python3
"""Turns gui/tokens.css, exported from the Paper file, into Swift constants.

Paper is where the palette is edited. Regenerate after exporting new values:
    python3 tools/gen_tokens.py
"""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
css = (root / "gui/tokens.css").read_text()
tokens = dict(re.findall(r"--([a-z0-9-]+):\s*([^;]+);", css))

# The default must render on any Mac. Fonts that are not redistributable belong in
# Settings on the machine that has them, not in the repository.
reading = tokens["font-reading"].strip().strip('"')
if not list((root / "gui/Fonts").glob(reading.replace(" ", "") + "*")):
    raise SystemExit(f"--font-reading is {reading!r}, which gui/Fonts does not bundle")


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


lines = ["// Generated by tools/gen_tokens.py from gui/tokens.css. Do not edit.", "", "enum Tokens {"]
for name, value in tokens.items():
    key = camel(name)
    if name.startswith("color-"):
        digits = value.strip().lstrip("#")
        if len(digits) == 6:
            digits += "FF"
        lines.append(f"    static let {key}: UInt32 = 0x{digits.upper()}")
    elif name.startswith("font-"):
        lines.append(f"    static let {key} = {value.strip()}")
    elif name.startswith("radius-"):
        lines.append(f"    static let {key}: Double = {value.strip().removesuffix('px')}")
lines += ["}", ""]
(root / "gui/Sources/Reader/Tokens.swift").write_text("\n".join(lines))
