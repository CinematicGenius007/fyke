#!/usr/bin/env python3
"""Turns gui/tokens.css, exported from the Paper file, into Swift, XAML and C# tokens.

Paper is where the palette is edited. Regenerate after exporting new values:
    python3 tools/gen_tokens.py
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
css = (root / "gui/tokens.css").read_text()
tokens = dict(re.findall(r"--([a-z0-9-]+):\s*([^;]+);", css))

# The default must render on any Mac. Fonts that are not redistributable belong in
# Settings on the machine that has them, not in the repository.
reading = tokens["font-reading"].strip().strip('"')
if not list((root / "gui/Fonts").glob(reading.replace(" ", "") + "*")):
    raise SystemExit(f"--font-reading is {reading!r}, which gui/Fonts does not bundle")


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


lines = ["// Generated by tools/gen_tokens.py from gui/tokens.css. Do not edit.", "", "enum Tokens {"]
for name, value in tokens.items():
    key = camel(name)
    if name.startswith("color-"):
        digits = value.strip().lstrip("#")
        if len(digits) == 6:
            digits += "FF"
        lines.append(f"    static let {key}: UInt32 = 0x{digits.upper()}")
    elif name.startswith("font-"):
        lines.append(f"    static let {key} = {value.strip()}")
    elif name.startswith("radius-"):
        lines.append(f"    static let {key}: Double = {value.strip().removesuffix('px')}")
lines += ["}", ""]
def output(path, content):
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Generated tokens are out of date: {path.relative_to(root)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


output(root / "gui/Sources/Reader/Tokens.swift", "\n".join(lines))

# The XAML compiler cannot read the brackets in the macOS file names, so the copies bundled
# with the Windows app swap the axis list for "-Variable": "Inter[opsz,wght].ttf" is
# "Inter-Variable.ttf". Each copy must match its original byte for byte.
mac_fonts = root / "gui/Fonts"
windows_fonts = root / "gui-windows/src/Fyke.App/Fonts"


def windows_font(family):
    stem = family.replace(" ", "")
    originals = [f for f in sorted(mac_fonts.iterdir()) if re.fullmatch(re.escape(stem) + r"(-Italic)?\[[^\]]+\]\.ttf", f.name)]
    if not originals:
        raise SystemExit(f"gui/Fonts has no variable font for {family!r}")
    for original in originals:
        copy = windows_fonts / re.sub(r"\[[^\]]+\]", "-Variable", original.name)
        if not copy.exists() or copy.read_bytes() != original.read_bytes():
            raise SystemExit(f"{copy.relative_to(root)} must be a copy of {original.relative_to(root)}")
    upright = next(f for f in originals if "-Italic" not in f.name)
    return re.sub(r"\[[^\]]+\]", "-Variable", upright.name)


# Fonts and radii sit in both theme dictionaries, beside the colours, because a theme may
# change them: the window reads them through ThemeResource and swaps them like the brushes.
look = []
for name, value in tokens.items():
    if name.startswith("font-"):
        family = value.strip().strip('"')
        key = camel(name); key = key[0].upper() + key[1:]
        look.append(f'      <FontFamily x:Key="{key}">ms-appx:///Fonts/{windows_font(family)}#{family}</FontFamily>')
        if key == "FontReading":
            # Titles are set in the reading face unless a theme says otherwise, as on macOS.
            look.append(f'      <FontFamily x:Key="FontTitle">ms-appx:///Fonts/{windows_font(family)}#{family}</FontFamily>')
    elif name.startswith("radius-"):
        key = camel(name); key = key[0].upper() + key[1:]
        look.append(f'      <CornerRadius x:Key="{key}">{value.strip().removesuffix("px")}</CornerRadius>')

# XAML uses #AARRGGBB, whereas CSS uses #RRGGBBAA.
xaml = ['<!-- Generated by tools/gen_tokens.py from gui/tokens.css. Do not edit. -->',
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        '  <ResourceDictionary.ThemeDictionaries>']
for theme in ("light", "dark"):
    xaml.append(f'    <ResourceDictionary x:Key="{theme.capitalize()}">')
    for name, value in tokens.items():
        prefix = f"color-{theme}-"
        if not name.startswith(prefix):
            continue
        key = camel(name.removeprefix(prefix))
        key = key[0].upper() + key[1:]
        digits = value.strip().lstrip("#")
        if len(digits) == 8:
            digits = digits[6:] + digits[:6]
        xaml.append(f'      <Color x:Key="{key}Color">#{digits.upper()}</Color>')
        xaml.append(f'      <SolidColorBrush x:Key="{key}Brush" Color="{{StaticResource {key}Color}}" />')
    xaml += look
    xaml.append('    </ResourceDictionary>')
xaml += ['  </ResourceDictionary.ThemeDictionaries>']
xaml += ['</ResourceDictionary>', '']
output(root / "gui-windows/src/Fyke.App/Themes/Tokens.xaml", "\n".join(xaml))

# The palette as RGBA values, as in Tokens.swift, so the Windows reader derives Newsprint,
# Terminal and the user's themes from the same numbers as macOS.
csharp = ["// Generated by tools/gen_tokens.py from gui/tokens.css. Do not edit.", "",
          "namespace Fyke.ViewModels;", "",
          "/// <summary>The Paper palette as RGBA values, with the typefaces and radii.</summary>",
          "internal static class Tokens", "{"]
for name, value in tokens.items():
    if name.startswith("color-"):
        digits = value.strip().lstrip("#")
        if len(digits) == 6:
            digits += "FF"
        key = camel(name); key = key[0].upper() + key[1:]
        csharp.append(f"    public const uint {key} = 0x{digits.upper()};")
    elif name.startswith("font-"):
        key = camel(name); key = key[0].upper() + key[1:]
        csharp.append(f'    public const string {key} = "{value.strip().strip(chr(34))}";')
    elif name.startswith("radius-"):
        key = camel(name); key = key[0].upper() + key[1:]
        csharp.append(f"    public const double {key} = {value.strip().removesuffix('px')};")
csharp += ["}", ""]
output(root / "gui-windows/src/Fyke.ViewModels/Tokens.g.cs", "\n".join(csharp))
