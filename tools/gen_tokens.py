#!/usr/bin/env python3
"""Turns gui/tokens.css, exported from the Paper file, into Swift constants.

Paper is where the palette is edited. Regenerate after exporting new values:
    python3 tools/gen_tokens.py
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
css = (root / "gui/tokens.css").read_text()
tokens = dict(re.findall(r"--([a-z0-9-]+):\s*([^;]+);", css))

# The default must render on any Mac. Fonts that are not redistributable belong in
# Settings on the machine that has them, not in the repository.
reading = tokens["font-reading"].strip().strip('"')
if not list((root / "gui/Fonts").glob(reading.replace(" ", "") + "*")):
    raise SystemExit(f"--font-reading is {reading!r}, which gui/Fonts does not bundle")


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(part.capitalize() for part in rest)


lines = ["// Generated by tools/gen_tokens.py from gui/tokens.css. Do not edit.", "", "enum Tokens {"]
for name, value in tokens.items():
    key = camel(name)
    if name.startswith("color-"):
        digits = value.strip().lstrip("#")
        if len(digits) == 6:
            digits += "FF"
        lines.append(f"    static let {key}: UInt32 = 0x{digits.upper()}")
    elif name.startswith("font-"):
        lines.append(f"    static let {key} = {value.strip()}")
    elif name.startswith("radius-"):
        lines.append(f"    static let {key}: Double = {value.strip().removesuffix('px')}")
lines += ["}", ""]
def output(path, content):
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != content:
            raise SystemExit(f"Generated tokens are out of date: {path.relative_to(root)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


output(root / "gui/Sources/Reader/Tokens.swift", "\n".join(lines))

# XAML uses #AARRGGBB, whereas CSS uses #RRGGBBAA.
xaml = ['<!-- Generated by tools/gen_tokens.py from gui/tokens.css. Do not edit. -->',
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
        '  <ResourceDictionary.ThemeDictionaries>']
for theme in ("light", "dark"):
    xaml.append(f'    <ResourceDictionary x:Key="{theme.capitalize()}">')
    for name, value in tokens.items():
        prefix = f"color-{theme}-"
        if not name.startswith(prefix):
            continue
        key = camel(name.removeprefix(prefix))
        key = key[0].upper() + key[1:]
        digits = value.strip().lstrip("#")
        if len(digits) == 8:
            digits = digits[6:] + digits[:6]
        xaml.append(f'      <Color x:Key="{key}Color">#{digits.upper()}</Color>')
        xaml.append(f'      <SolidColorBrush x:Key="{key}Brush" Color="{{StaticResource {key}Color}}" />')
    xaml.append('    </ResourceDictionary>')
xaml += ['  </ResourceDictionary.ThemeDictionaries>']
# The XAML compiler cannot read the brackets in the macOS file names, so the copies bundled
# with the Windows app are named without them.
fonts = {"Inter": "Inter-Variable.ttf", "Newsreader": "Newsreader-Variable.ttf",
         "JetBrains Mono": "JetBrainsMono-Variable.ttf"}
for name, value in tokens.items():
    if name.startswith("font-"):
        family = value.strip().strip('"')
        key = camel(name); key = key[0].upper() + key[1:]
        xaml.append(f'  <FontFamily x:Key="{key}">ms-appx:///Fonts/{fonts[family]}#{family}</FontFamily>')
    elif name.startswith("radius-"):
        key = camel(name); key = key[0].upper() + key[1:]
        xaml.append(f'  <CornerRadius x:Key="{key}">{value.strip().removesuffix("px")}</CornerRadius>')
xaml += ['</ResourceDictionary>', '']
output(root / "gui-windows/src/Fyke.App/Themes/Tokens.xaml", "\n".join(xaml))
