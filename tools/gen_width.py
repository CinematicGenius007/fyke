#!/usr/bin/env python3
"""Generates src/width_table.zig from Python's Unicode database.

Usage: gen_width.py > src/width_table.zig
"""
import sys, unicodedata

def ranges(predicate):
    out, start = [], None
    for cp in range(0x110000):
        if 0xD800 <= cp < 0xE000: hit = False
        else: hit = predicate(chr(cp))
        if hit and start is None: start = cp
        if not hit and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out

def zero(c):
    return unicodedata.category(c) in ("Mn", "Me", "Cf") and c != "\u00ad"

def wide(c):
    return unicodedata.east_asian_width(c) in ("W", "F") and not zero(c)

def emit(name, rows):
    print(f"pub const {name} = [_][2]u21{{")
    for a, b in rows: print(f"    .{{ 0x{a:X}, 0x{b:X} }},")
    print("};\n")

print(f"//! Generated by tools/gen_width.py from Unicode {unicodedata.unidata_version}. Do not edit.\n")
emit("zero_width", ranges(zero))
emit("wide", ranges(wide))
